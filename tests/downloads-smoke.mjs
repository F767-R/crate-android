import assert from 'node:assert/strict';
globalThis.localStorage={getItem:()=>null,setItem(){}};
let ids=['B'], fail=false;
globalThis.window={Capacitor:{Plugins:{MediaBridge:{async getDownloadedTracks(){if(fail)throw new Error('gone');return {itemIds:ids};}}}}};
const state=await import('../src/stores/state.js');
const {downloadedOnly}=await import('../src/stores/offline.js');
const downloads=await import('../src/utils/downloads.js');
state.allTracks.value=[{Id:'A',AlbumId:'one'},{Id:'B',AlbumId:'two'}];
state.allAlbums.value=[{Id:'one'},{Id:'two'}];
await downloads.refreshDownloads();
assert.equal(downloads.visibleLibraryTracks.value.length,2);
downloadedOnly.value=true;
assert.deepEqual(downloads.visibleLibraryTracks.value.map(t=>t.Id),['B']);
assert.deepEqual(downloads.visibleLibraryAlbums.value.map(t=>t.Id),['two']);
ids=['A']; await downloads.refreshDownloads();
assert.deepEqual(downloads.visibleLibraryTracks.value.map(t=>t.Id),['A'],'evictions and new downloads update the filter');
ids=[]; await downloads.refreshDownloads();
assert.equal(downloads.visibleLibraryAlbums.value.length,0);
ids=['B']; await downloads.refreshDownloads();
fail=true; await downloads.refreshDownloads();
assert.equal(downloads.downloadsError.value,true);
assert.equal(downloads.downloadedIds.value.size,0,'failed cache reads cannot leave stale downloaded badges');
fail=false; ids=['B']; await downloads.refreshDownloads();
assert.equal(downloads.downloadsError.value,false);
downloadedOnly.value=false;
assert.equal(downloads.visibleLibraryTracks.value.length,2);
console.log('Downloaded filter passed: actual cache IDs, album/track filtering, eviction, empty cache and retry.');
