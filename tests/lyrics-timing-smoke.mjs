import assert from 'node:assert/strict';
import { lyricPosition, currentGroupIndex, createLyricClock, wordProgress, wordGlow, wordScale } from '../src/utils/lyricsTiming.js';
import { groupLyricsLines } from '../src/utils/lrcParser.js';
const groups = groupLyricsLines([{ time: 1, text: 'Original' }, { time: 1, text: 'Translation' }, { time: 1.2, text: 'Next' }]);
assert.equal(groups.length, 2);
assert.equal(currentGroupIndex(groups, .9), -1);
assert.equal(currentGroupIndex(groups, lyricPosition(1, 250, true, false)), 1, 'cross a boundary between native samples');
assert.equal(currentGroupIndex(groups, lyricPosition(1, 250, false, false)), 0, 'pause freezes timing');
assert.equal(currentGroupIndex(groups, lyricPosition(1, 250, true, true)), 0, 'buffering freezes timing');
assert.equal(lyricPosition(1, 10000, true, false), 1.75, 'stale samples cannot advance indefinitely');
assert.equal(currentGroupIndex(groups, lyricPosition(.5, 0, true, false)), -1, 'backward seek resets immediately');
console.log('Lyrics timing passed: grouped translations, boundaries, pause, buffering, stale samples, seek.');

const clock = createLyricClock();
clock.sample(1, 0, true, false);
assert.equal(clock.read(300), 1.3);
clock.sample(1.25, 300, true, false);
assert.equal(clock.read(300), 1.3, 'late forward sample cannot rewind the painted word');
assert.equal(clock.read(400), 1.35, 'clock catches up without accumulating delay');
clock.sample(1.1, 400, true, false);
assert.equal(clock.read(400), 1.1, 'even a small backward seek resets immediately');
clock.sample(8, 500, true, false);
assert.equal(clock.read(500), 8, 'forward seek resets without easing through skipped words');
clock.sample(8.1, 600, false, false);
assert.equal(clock.read(1600), 8.1, 'pause freezes at the actual sample');
clock.sample(8.1, 1600, true, true);
assert.equal(clock.read(2600), 8.1, 'buffering freezes at the actual sample');
clock.sample(8.1, 2600, true, false);
assert.equal(clock.read(3600), 8.85, 'resume keeps the stale-sample cap');
assert.equal(clock.read(4600), 8.85);
const rapidWord = {start:1, end:1.08};
assert.equal(wordGlow(rapidWord, .5), 0, 'rapid syllables must not flash');
assert.ok(wordProgress(rapidWord, 1.04) > .49, 'rapid syllables retain accurate fill');
const heldWord = {start:1, end:2};
assert.equal(wordGlow(heldWord, 0), 0);
assert.equal(wordGlow(heldWord, 1), 0, 'glow fades before active state is removed');
assert.equal(wordGlow(heldWord, .5), 1);
assert.equal(wordGlow(heldWord, .5, true), 0);
assert.equal(wordGlow({start:1}, .5), 0);
console.log('Rapid lyrics passed: forward sample stability, small seeks, pause/buffering, stale cap and non-flashing glow.');

assert.equal(wordScale(.5), 1.05, 'all timed words peak at 105%');
assert.ok(Math.abs(wordScale(wordProgress(rapidWord, 1.04)) - 1.05) < .00001, '80ms syllables also reach 105%');
assert.equal(wordScale(0), 1);
assert.equal(wordScale(1), 1, 'scale settles before the word finishes');
assert.equal(wordScale(.5, true), 1, 'reduced motion keeps the text still');
assert.ok(Math.abs(wordScale(.25) - wordScale(.75)) < .00001, 'enlargement eases in and out symmetrically');
