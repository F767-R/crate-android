import assert from 'node:assert/strict';
import { createLibraryRequestOwner } from '../src/utils/libraryRequestOwner.js';

const deferred = () => {
  let resolve;
  let reject;
  const promise = new Promise((yes, no) => { resolve = yes; reject = no; });
  return { promise, resolve, reject };
};
const outcome = promise => promise.then(value => ({ value }), error => ({ error }));
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
let context = { user: 'one', library: 'music' };
const loads = [];
const commits = [];
const owner = createLibraryRequestOwner({ getContext: () => context });
const load = (scope, options) => {
  const task = { ...deferred(), scope, signal: options.signal };
  loads.push(task);
  return task.promise;
};
const run = (options = {}) => owner.run('tracks', load, value => commits.push(value), options);

const firstConsumer = new AbortController();
const first = outcome(run({ signal: firstConsumer.signal }));
const shared = outcome(run());
await tick();
assert.equal(loads.length, 1, 'same-generation consumers share a request');
firstConsumer.abort();
assert.equal((await first).error.code, 'aborted');
assert.equal(loads[0].signal.aborted, false, 'one leaving consumer must not cancel the remaining subscriber');
loads[0].resolve('initial');
assert.equal((await shared).value, 'initial');
assert.deepEqual(commits, ['initial']);

const stale = outcome(run());
await tick();
owner.invalidate();
const fresh = outcome(run());
const joinedFresh = outcome(run());
await tick();
assert.equal((await stale).error.code, 'aborted');
assert.equal(loads[1].signal.aborted, true);
assert.equal(loads.length, 3, 'refresh starts one new request instead of joining the old one');
loads[1].resolve('stale success');
await tick();
const joinedAfterLateSuccess = outcome(run());
assert.equal(loads.length, 3, 'an old finally must not remove the new request owner');
loads[2].resolve('fresh');
assert.equal((await fresh).value, 'fresh');
assert.equal((await joinedFresh).value, 'fresh');
assert.equal((await joinedAfterLateSuccess).value, 'fresh');
assert.deepEqual(commits, ['initial', 'fresh']);

const rejectedOld = outcome(run());
await tick();
owner.invalidate();
const afterRejection = outcome(run());
await tick();
loads[3].reject(new Error('late obsolete failure'));
assert.equal((await rejectedOld).error.code, 'aborted');
const anotherFreshSubscriber = outcome(run());
await tick();
assert.equal(loads.length, 5, 'late failures cannot clear a newer in-flight request');
loads[4].resolve('after late rejection');
await Promise.all([afterRejection, anotherFreshSubscriber]);
assert.deepEqual(commits, ['initial', 'fresh', 'after late rejection']);

const previousScope = outcome(run());
await tick();
context = { user: 'two', library: 'music' };
const nextScope = outcome(run());
await tick();
assert.equal((await previousScope).error.code, 'aborted');
assert.equal(loads[5].signal.aborted, true);
assert.equal(loads[6].scope.user, 'two');
loads[5].resolve('wrong user');
loads[6].resolve('right user');
assert.equal((await nextScope).value, 'right user');
assert.equal(commits.includes('wrong user'), false);

const onlyConsumer = new AbortController();
const abandoned = outcome(run({ signal: onlyConsumer.signal }));
await tick();
onlyConsumer.abort();
assert.equal((await abandoned).error.code, 'aborted');
assert.equal(loads[7].signal.aborted, true, 'the last subscriber leaving aborts unused work');

// Exercise the actual shared data layer with entirely mocked network responses.
globalThis.localStorage = { getItem: () => null, setItem() {} };
const state = await import('../src/stores/state.js');
const library = await import('../src/utils/libraryData.js');
state.userId.value = 'test-user';
state.musicLibraryId.value = 'test-library';
const requests = [];
globalThis.fetch = async (input, options) => {
  const url = new URL(input);
  const task = { ...deferred(), signal: options.signal, path: url.pathname, parent: url.searchParams.get('ParentId'), type: url.searchParams.get('IncludeItemTypes') };
  requests.push(task);
  return { ok: true, json: () => task.promise };
};
const oldAlbums = outcome(library.ensureAlbumsLoaded());
const oldTracks = outcome(library.ensureAllTracksLoaded());
const oldDetail = outcome(library.ensureAlbumDetailLoaded('album'));
await tick();
assert.equal(requests.length, 4);
const beforeRefresh = library.libraryGeneration.value;
const refreshed = outcome(library.refreshLibrary());
const freshAlbums = outcome(library.ensureAlbumsLoaded());
await tick();
assert.equal(library.libraryGeneration.value, beforeRefresh + 1);
assert.equal(state.allTracksFetched.value, false);
assert.equal(state.albumDetailCache.value.size, 0);
assert.ok(requests.slice(0, 4).every(request => request.signal.aborted));
assert.equal(requests.length, 5, 'MainView and Header share the refreshed album request');
requests[0].resolve({ Items: [{ Id: 'old-album' }] });
requests[1].resolve({ Items: [{ Id: 'old-track' }] });
requests[2].resolve({ Id: 'album', Name: 'Old detail' });
requests[3].resolve({ Items: [{ Id: 'old-detail-track' }] });
for (const result of await Promise.all([oldAlbums, oldTracks, oldDetail])) assert.equal(result.error.code, 'aborted');
requests[4].resolve({ Items: [{ Id: 'new-album' }] });
await Promise.all([refreshed, freshAlbums]);
assert.deepEqual(state.allAlbums.value, [{ Id: 'new-album' }]);
assert.deepEqual(state.allTracks.value, []);
assert.equal(state.albumDetailCache.value.size, 0, 'late details cannot repopulate the invalidated cache');

const newDetail = outcome(library.ensureAlbumDetailLoaded('album'));
const joinedDetail = outcome(library.ensureAlbumDetailLoaded('album'));
await tick();
assert.equal(requests.length, 7);
requests[5].resolve({ Id: 'album', Name: 'Fresh detail' });
requests[6].resolve({ Items: [{ Id: 'fresh-track' }] });
assert.equal((await newDetail).value.Name, 'Fresh detail');
await joinedDetail;
const cachedDetail = await library.ensureAlbumDetailLoaded('album');
assert.deepEqual(cachedDetail.Items, [{ Id: 'fresh-track' }]);
assert.equal(requests.length, 7, 'the normalized detail cache serves subsequent views without a refetch');
library.invalidateLibrary();
assert.equal(state.albumDetailCache.value.size, 0);

const offline = await import('../src/stores/offline.js');
state.allAlbums.value = [{ Id: 'visible-album' }];
state.allTracks.value = [{ Id: 'visible-track' }];
const failedRefresh = outcome(library.refreshLibrary());
await tick();
assert.equal(state.allAlbums.value[0].Id, 'visible-album', 'refresh keeps displayed albums while waiting');
assert.equal(state.allTracks.value[0].Id, 'visible-track', 'search keeps its displayed tracks while waiting');
requests.at(-1).reject(new Error('connection lost'));
assert.ok((await failedRefresh).error);
assert.equal(state.allAlbums.value[0].Id, 'visible-album', 'a failed refresh must not erase displayed albums');

const olderIndex = outcome(library.syncLibraryIndex());
await tick();
const oldIndexRequest = requests.at(-1);
const nextRefresh = outcome(library.refreshLibrary());
const newerIndex = outcome(library.syncLibraryIndex());
await tick();
assert.equal((await olderIndex).error.code, 'aborted');
assert.equal(offline.libraryIndexing.value, true, 'old index cleanup cannot hide a newer sync');
oldIndexRequest.resolve({ Items: [{ Id: 'obsolete-track' }] });
requests.at(-2).resolve({ Items: [{ Id: 'replacement-album' }] });
requests.at(-1).resolve({ Items: [{ Id: 'replacement-track' }] });
await Promise.all([nextRefresh, newerIndex]);
assert.equal(offline.libraryIndexing.value, false);
assert.equal(offline.libraryIndexError.value, false);
assert.equal(state.allTracks.value[0].Id, 'replacement-track');
console.log('library state smoke test passed');
